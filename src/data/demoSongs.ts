import type { Song, MusicNote } from '../types/music';
import { midiToName } from '../types/music';

// ─── Demo Songs ──────────────────────────────────────────────────────────────

function buildNote(
  id: string,
  midi: number,
  startTime: number,
  duration: number,
  hand: 'left' | 'right',
  velocity = 80,
  finger?: number
): MusicNote {
  return { id, midi, name: midiToName(midi), startTime, duration, hand, velocity, finger };
}

